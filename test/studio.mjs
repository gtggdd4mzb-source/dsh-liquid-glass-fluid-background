import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { createServer } from 'node:http';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const script = await readFile(new URL('../lib/glass-client.js',import.meta.url),'utf8');
const fixture = await readFile(new URL('./fixture.html',import.meta.url),'utf8');
const server = createServer((_,res)=>{res.setHeader('content-type','text/html;charset=utf-8');res.end(fixture.replace('</body>',`<script>${script}</script></body>`));});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const browser = await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
const context=await browser.newContext({locale:'zh-CN',viewport:{width:1280,height:1000}});
await context.addInitScript(()=>localStorage.setItem('dsh.liquid-glass.v1',JSON.stringify({...JSON.parse(localStorage.getItem('dsh.liquid-glass.v1')||'{}'),startup:false})));
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const ui=page.locator('#dsh-liquid-glass-ui');
const field=key=>ui.locator(`[data-field="${key}"]`);
const palette=i=>ui.locator(`input[type=color][data-color="${i}"]`);
const tab=key=>ui.locator(`[data-tab="${key}"]`).click();
const backdrop=page.locator('#dsh-liquid-glass-backdrop');
const value=name=>page.locator('body').evaluate((n,name)=>getComputedStyle(n).getPropertyValue(name).trim(),name);
try{
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await ui.locator('.launcher').click();
  await field('speed').fill('200');
  assert.equal(await value('--dsh-lg-duration'),'16s');
  await field('speed').fill('50');
  assert.equal(await value('--dsh-lg-duration'),'64s');
  for(const [flow,name]of [['drift','dsh-lg-drift'],['wave','dsh-lg-wave'],['orbit','dsh-lg-orbit'],['aurora','dsh-lg-aurora']]){
    await field('flow').selectOption(flow);
    assert.equal(await backdrop.locator('.dsh-lg-blob').first().evaluate(n=>getComputedStyle(n).animationName),name);
  }
  await field('motion').uncheck();
  assert.equal(await backdrop.locator('.dsh-lg-blob').first().evaluate(n=>getComputedStyle(n).animationPlayState),'paused');
  await field('motion').check();
  await field('amount').fill('0');
  assert.equal(await backdrop.locator('.dsh-lg-blob').first().evaluate(n=>getComputedStyle(n).animationPlayState),'paused');
  await field('amount').fill('75');
  assert.equal(await value('--dsh-lg-travel'),'30vw');
  console.log('PASS speed, all four flow modes, pause, zero amplitude and live CSS variables');

  await ui.locator('[data-preset="sunset"]').click();
  assert.equal(await field('preset').inputValue(),'sunset');
  assert.equal(await palette(0).inputValue(),'#f1bb92');
  await palette(0).fill('#19a8cc');
  assert.equal(await field('preset').inputValue(),'custom');
  assert.equal(await palette(1).inputValue(),'#ed9db8');
  await ui.locator('input[type=text][data-color="1"]').fill('#ef88b8');
  await ui.locator('input[type=text][data-color="1"]').press('Tab');
  assert.equal(await palette(1).inputValue(),'#ef88b8');
  await field('depth').fill('0'); const light=await value('--dsh-lg-c1');
  await field('depth').fill('100'); const deep=await value('--dsh-lg-c1');
  const sum=hex=>hex.slice(1).match(/../g).reduce((sum,v)=>sum+parseInt(v,16),0);
  assert.ok(sum(light)>sum(deep));
  await field('depth').fill('45');
  await field('colorSaturation').fill('130');
  assert.equal(await value('--dsh-lg-richness'),'130%');
  await ui.locator('.close').click();
  await page.reload();
  await ui.locator('.launcher').click();
  assert.equal(await field('preset').inputValue(),'custom');
  assert.equal(await palette(0).inputValue(),'#19a8cc');
  assert.equal(await palette(1).inputValue(),'#ef88b8');
  assert.equal(await field('flow').inputValue(),'aurora');
  assert.equal(await field('speed').inputValue(),'50');
  assert.equal(await field('depth').inputValue(),'45');
  console.log('PASS preset swatches, custom four-color palette, HEX, color depth and persisted controls');

  await page.evaluate(()=>window.dispatchEvent(new StorageEvent('storage',{key:'dsh.liquid-glass.v1',newValue:JSON.stringify({startup:false,preset:'custom',speed:9999,amount:-20,depth:'invalid',flow:'__proto__',customColors:['url(https://example.invalid)',null,'#abcdef','#123456']})})));
  assert.equal(await field('speed').inputValue(),'300');
  assert.equal(await field('amount').inputValue(),'0');
  assert.equal(await field('depth').inputValue(),'50');
  assert.equal(await field('flow').inputValue(),'drift');
  assert.equal(await palette(0).inputValue(),'#cbb4cf');
  assert.equal(await palette(2).inputValue(),'#abcdef');
  await field('amount').fill('55');
  await field('speed').fill('100');
  await ui.locator('[data-preset="aurora"]').click();
  console.log('PASS untrusted palette strings, malformed modes and invalid numeric settings are normalized');

  await tab('material');
  await field('blur').fill('3');
  await field('refraction').fill('36');
  await page.waitForFunction(()=>document.querySelector('[data-dsh-lg-lens]'));
  assert.ok(await page.locator('[data-dsh-lg-lens]').count()<=8);
  const lens=page.locator('[data-dsh-lg-lens]').first();
  assert.match(await lens.evaluate(n=>getComputedStyle(n).backdropFilter),/url/);
  assert.equal(await lens.evaluate(n=>getComputedStyle(n).filter),'none');
  await page.mouse.move(650,400);
  assert.ok(await lens.evaluate(n=>n.style.getPropertyValue('--dsh-lg-light-x')));
  await field('refraction').fill('0');
  assert.equal(await page.locator('[data-dsh-lg-lens]').count(),0);
  assert.equal(await page.locator('.dsh-lg-sheen').count(),0);
  await field('refraction').fill('36');
  await page.waitForFunction(()=>document.querySelector('[data-dsh-lg-lens]'));
  await page.emulateMedia({forcedColors:'active'});
  await page.waitForFunction(()=>!document.querySelector('[data-dsh-lg-lens]'));
  await page.emulateMedia({forcedColors:'none',reducedMotion:'reduce'});
  assert.equal(await backdrop.locator('.dsh-lg-blob').first().evaluate(n=>getComputedStyle(n).animationPlayState),'paused');
  await page.emulateMedia({reducedMotion:'no-preference'});
  console.log('PASS bounded backdrop-only displacement, pointer light, refraction off and accessibility recovery');

  await tab('background');
  await mkdir(new URL('../assets/',import.meta.url),{recursive:true});
  await page.screenshot({path:fileURLToPath(new URL('../assets/studio-palette.png',import.meta.url)),fullPage:true});
  await ui.locator('.close').click();
  // Isolate the optical renderer over a high-contrast grid to prove actual pixel displacement.
  await page.evaluate(()=>window[Symbol.for('dsh.liquid-glass.runtime')].dispose());
  await page.addStyleTag({content:`body{background:repeating-linear-gradient(90deg,#122b52 0 5px,transparent 5px 28px),repeating-linear-gradient(0deg,#39b8dc 0 5px,#e8f6ff 5px 28px)!important}.app{visibility:hidden}#optical-test{position:fixed;left:300px;top:240px;width:540px;height:280px;border-radius:46px;background:#ffffff12}#optical-test[data-dsh-lg-lens]{backdrop-filter:var(--dsh-lg-lens-filter)}`});
  await page.evaluate(()=>{const n=document.createElement('div');n.id='optical-test';document.body.append(n);});
  const box={x:290,y:230,width:560,height:300};
  const before=await page.screenshot({clip:box});
  await page.evaluate(code=>{
    const get=new Function(code+';return createGlassOptics;')();window.__optical=get();
    window.__optical.sync([document.getElementById('optical-test')],{enabled:true,refraction:42,blur:0,saturate:100,shine:0,interactive:false});
  },await readFile(new URL('../src/optics.js',import.meta.url),'utf8'));
  const after=await page.screenshot({clip:box});
  assert.notDeepEqual(before,after,'the grid must visibly bend with zero blur and zero sheen');
  await page.screenshot({path:fileURLToPath(new URL('../assets/refraction-grid.png',import.meta.url)),clip:box});
  await page.evaluate(()=>window.__optical.dispose());
  const restored=await page.screenshot({clip:box});
  assert.deepEqual(restored,before,'optical cleanup must restore the exact original pixels');
  assert.equal(await page.locator('#optical-test').evaluate(n=>n.style.getPropertyValue('position')),'');
  console.log('PASS grid pixels change from refraction alone and restore byte-for-byte on disposal');
  assert.deepEqual(errors,[]);
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
